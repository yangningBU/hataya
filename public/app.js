const results = $('#results');
const status = $('#status');
const intro = $('#intro');
const input = $('#q');

function renderResults() {
  const cur = state.current;
  results.replaceChildren();
  if (!cur) return;
  const list = cur.ai || cur.local;
  for (const r of list) results.append((CARD[r.entry.type] || otherCard)(r));
  if (cur.local.length && !cur.ai && !cur.english) {
    results.append(h('div', { class: 'more' },
      h('button', { class: 'linklike', type: 'button', onclick: () => runAI(cur.query) }, 'Not the word you meant? Ask AI'),
    ));
  }
}

function setStatus(...nodes) {
  status.replaceChildren(...nodes);
}

function search(query, { fromSubmit = false } = {}) {
  const q = query.trim();
  updateUrl(q);
  intro.hidden = !!q;
  if (!q) {
    state.current = null;
    setStatus();
    renderResults();
    return;
  }
  const { results: local, english } = lookup(q);
  state.current = { query: q, local, english, ai: null };
  setStatus();

  if (!local.length) {
    const cached = store.get(aiKey(q), null);
    if (cached || fromSubmit) runAI(q);
    else {
      setStatus(h('div', { class: 'notice' },
        h('p', {}, 'Not in the offline dictionary.'),
        h('p', {}, 'Press Enter to ask AI, or check the spelling.'),
        h('div', { class: 'actions' }, h('button', { class: 'btn', type: 'button', onclick: () => runAI(q) }, '✦ Ask AI')),
      ));
    }
  }
  renderResults();
}

async function runAI(q) {
  if (!state.current || state.current.query !== q) return;
  setStatus(h('div', { class: 'notice' }, h('p', {}, h('span', { class: 'spinner' }), 'Asking AI about ', he(q), '… this can take a few seconds.')));
  try {
    const ai = await askAI(q);
    if (state.current?.query !== q) return;
    if (!ai.length) {
      setStatus(h('div', { class: 'notice' }, h('p', {}, 'The AI didn’t recognize this word. Check the spelling and try again.')));
      return;
    }
    state.current.ai = ai;
    setStatus();
    renderResults();
  } catch (err) {
    if (err.name === 'AbortError' || state.current?.query !== q) return;
    setStatus(h('div', { class: 'notice' },
      h('p', {}, err.message),
      h('div', { class: 'actions' }, h('button', { class: 'btn secondary', type: 'button', onclick: () => runAI(q) }, 'Try again')),
    ));
  }
}

function updateUrl(q) {
  const url = new URL(location.href);
  if (q) url.searchParams.set('q', q);
  else url.searchParams.delete('q');
  history.replaceState(null, '', url);
}

