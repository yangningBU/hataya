const TENSES = {
  past: ['Past', 'עָבָר'],
  present: ['Present', 'הוֹוֶה'],
  future: ['Future', 'עָתִיד'],
  imperative: ['Imperative', 'צִוּוּי'],
  infinitive: ['Infinitive', 'שֵׁם הַפֹּעַל'],
};

const PRONOUNS = {
  '1s': ['אֲנִי', 'I'],
  '2ms': ['אַתָּה', 'you (m.)'],
  '2fs': ['אַתְּ', 'you (f.)'],
  '3ms': ['הוּא', 'he'],
  '3fs': ['הִיא', 'she'],
  '1p': ['אֲנַחְנוּ', 'we'],
  '2mp': ['אַתֶּם', 'you (m. pl.)'],
  '2fp': ['אַתֶּן', 'you (f. pl.)'],
  '3p': ['הֵם / הֵן', 'they'],
  '3mp': ['הֵם', 'they (m.)'],
  '3fp': ['הֵן', 'they (f.)'],
};
const NUMBER_GENDER = {
  ms: ['Masculine singular', 'זָכָר יָחִיד'],
  fs: ['Feminine singular', 'נְקֵבָה יְחִידָה'],
  mp: ['Masculine plural', 'זָכָר רַבִּים'],
  fp: ['Feminine plural', 'נְקֵבָה רַבּוֹת'],
};
const GENDER = {
  m: ['♂', 'Masculine', 'זָכָר'],
  f: ['♀', 'Feminine', 'נְקֵבָה'],
  mf: ['⚥', 'Masculine or feminine', 'זָכָר וּנְקֵבָה'],
};
const TYPE = { noun: ['Noun', 'שֵׁם עֶצֶם'], verb: ['Verb', 'פֹּעַל'], adjective: ['Adjective', 'שֵׁם תֹּאַר'], other: ['Word', 'מִלָּה'] };

function describeMatch(where) {
  if (!where) return '';
  switch (where.kind) {
    case 'singular': return 'singular';
    case 'plural': return 'plural';
    case 'ms': case 'fs': case 'mp': case 'fp': return NUMBER_GENDER[where.kind][0].toLowerCase();
    case 'verb': {
      const t = TENSES[where.tense][0].toLowerCase();
      if (!where.slot) return t;
      if (where.tense === 'present' || where.tense === 'imperative') return `${t}, ${NUMBER_GENDER[where.slot][0].toLowerCase()}`;
      return `${t}, ${PRONOUNS[where.slot][1]}`;
    }
    default: return '';
  }
}

const isHit = (matches, tense, slot) =>
  (matches || []).some((w) => w.kind === 'verb' && w.tense === tense && (slot == null || w.slot === slot));

// ---------------------------------------------------------------- cards

function cardHead(entry) {
  const [en, heType] = TYPE[entry.type] || TYPE.other;
  return h('div', { class: 'card-head' },
    h('div', {},
      he(show(entry.lemma), { class: 'lemma', title: other(entry.lemma) }),
      entry.gloss ? h('p', { class: 'gloss' }, entry.gloss) : null,
    ),
    h('div', { class: 'badges' },
      h('span', { class: 'pill badge type' }, en, ' · ', he(heType)),
      entry.source === 'ai' ? h('span', { class: 'pill badge ai', title: 'Generated by AI. It may contain mistakes.' }, '✦ AI') : null,
    ),
  );
}

function matchLine(result) {
  const parts = [];
  if (result.entry.source === 'ai' && result.entry.matchedText) parts.push(result.entry.matchedText);
  else {
    const seen = new Set();
    for (const w of result.matches || []) {
      const d = describeMatch(w);
      if (d && !seen.has(d)) { seen.add(d); parts.push(d); }
    }
  }
  if (!parts.length && !result.prefix) return null;
  let text = parts.length ? `You typed: ${parts.slice(0, 3).join(' / ')}` : '';
  if (result.prefix) text += `${text ? ' ' : ''}(with the prefix ${result.prefix}־)`;
  if (result.approximate) text += ' (spelling variant)';
  return h('p', { class: 'match' }, text);
}

function nounNotes(entry) {
  const notes = [];
  const sg = entry.lemma?.p || '';
  const pl = entry.plural?.p || '';
  if (entry.gender === 'f' && sg && !/[הת]$/.test(sg)) notes.push('Feminine even though it doesn’t end in ־ה or ־ת.');
  if (entry.gender === 'm' && /ה$/.test(sg) && !/[ֶ]ה$/.test(entry.lemma.n)) notes.push('Masculine even though it ends in ־ה.');
  if (entry.gender === 'm' && /ות$/.test(pl)) notes.push('Masculine, but its plural ends in ־וֹת.');
  if (entry.gender === 'f' && /ים$/.test(pl) && !/יים$/.test(pl)) notes.push('Feminine, but its plural ends in ־ִים.');
  if (/ַיִם$/.test(entry.plural?.n || '')) notes.push('The plural is a dual form (־ַיִם), used for pairs.');
  if (entry.note) notes.push(entry.note);
  return [...new Set(notes)];
}

function nounCard(result) {
  const { entry } = result;
  const g = GENDER[entry.gender];
  const hitPl = result.matches?.some((w) => w.kind === 'plural');
  const hitSg = result.matches?.some((w) => w.kind === 'singular');
  return h('article', { class: 'card' },
    cardHead(entry),
    matchLine(result),
    g ? h('div', { class: `gender ${entry.gender}` }, h('span', { class: 'sym', 'aria-hidden': 'true' }, g[0]), g[1], he(g[2], { class: 'he' })) : null,
    h('div', { class: 'grid2' },
      formCell('Singular', 'יָחִיד', entry.lemma, hitSg),
      formCell('Plural', 'רַבִּים', entry.plural, hitPl, 'no plural'),
    ),
    ...nounNotes(entry).map((n) => h('p', { class: 'note' }, n)),
    sourceLine(entry),
  );
}

function formCell(label, heLabel, f, hit, emptyText = '—', cls = '') {
  return h('div', { class: `cell ${cls} ${hit ? 'hit' : ''} ${f ? '' : 'empty'}` },
    h('div', { class: 'label' }, h('span', {}, label), he(heLabel)),
    f ? he(show(f), { class: 'val', title: other(f) }) : h('div', { class: 'val' }, emptyText),
  );
}

function adjectiveCard(result) {
  const { entry } = result;
  const hit = (k) => result.matches?.some((w) => w.kind === k);
  const f = entry.forms || {};
  return h('article', { class: 'card' },
    cardHead(entry),
    matchLine(result),
    h('div', { class: 'grid2' },
      formCell('Masc. singular', 'זָכָר', f.ms, hit('ms'), '—', 'm'),
      formCell('Fem. singular', 'נְקֵבָה', f.fs, hit('fs'), '—', 'f'),
      formCell('Masc. plural', 'זָכָר רַבִּים', f.mp, hit('mp'), '—', 'm'),
      formCell('Fem. plural', 'נְקֵבָה רַבּוֹת', f.fp, hit('fp'), '—', 'f'),
    ),
    entry.note ? h('p', { class: 'note' }, entry.note) : null,
    sourceLine(entry),
  );
}

function tenseTable(tense, forms, matches) {
  const rows = SLOTS[tense].map((slot) => {
    const f = forms[slot];
    const [heLabel, enLabel] = tense === 'present' || tense === 'imperative'
      ? [NUMBER_GENDER[slot][1], NUMBER_GENDER[slot][0]]
      : PRONOUNS[slot];
    const label = [he(heLabel, { class: 'pro-he' }), h('span', { class: 'pro-en' }, enLabel)];
    const formal = tense === 'future' && (slot === '2fp' || slot === '3fp') && f;
    return h('tr', { class: isHit(matches, tense, slot) ? 'hit' : '' },
      h('td', { class: 'pro' }, ...label),
      f ? h('td', { class: 'form', lang: 'he', dir: 'rtl', title: other(f) }, show(f), formal ? h('span', { class: 'formal', lang: 'en', dir: 'ltr' }, 'formal') : null)
        : h('td', { class: 'form none' }, '—'),
    );
  });
  return h('table', { class: 'forms' }, h('tbody', {}, rows));
}

function verbCard(result) {
  const { entry } = result;
  const conj = entry.conj || {};
  const b = BINYANIM[entry.binyan];
  const letters = [...(entry.root || '')];
  if (letters.length) letters[letters.length - 1] = toFinal(letters[letters.length - 1]);
  const rootLetters = letters.join('־');
  const anyHit = (t) => isHit(result.matches, t);
  const nothingHit = !Object.keys(TENSES).some(anyHit);
  const section = (tense, body, caption) =>
    h('details', { class: 'tense', open: anyHit(tense) || nothingHit || tense !== 'imperative' },
      h('summary', {}, TENSES[tense][0], he(TENSES[tense][1], { class: 'he' })),
      body,
      caption ? h('p', { class: 'caption' }, caption) : null,
    );

  return h('article', { class: 'card' },
    cardHead(entry),
    matchLine(result),
    h('div', { class: 'verb-meta' },
      entry.root ? h('span', { class: 'meta' }, h('b', {}, 'Root '), he(rootLetters, { class: 'root-letters' })) : null,
      b ? h('span', { class: 'meta' }, h('b', {}, 'Binyan '), b.en, ' · ', he(b.he)) : null,
      entry.gizra === 'irregular' ? h('span', { class: 'meta' }, 'Irregular') : null,
    ),
    conj.infinitive ? h('div', { class: `inf cell ${anyHit('infinitive') ? 'hit' : ''}` },
      h('div', { class: 'label' }, h('span', {}, 'Infinitive'), he('שֵׁם הַפֹּעַל')),
      he(show(conj.infinitive), { class: 'val', title: other(conj.infinitive) }),
    ) : null,
    conj.past ? section('past', tenseTable('past', conj.past, result.matches)) : null,
    conj.present ? section('present', tenseTable('present', conj.present, result.matches),
      'The present tense works like an adjective: it agrees in gender and number, not person.') : null,
    conj.future ? section('future', tenseTable('future', conj.future, result.matches),
      'In everyday speech, אַתֶּן and הֵן usually take the masculine plural forms instead of the formal ־נָה forms.') : null,
    conj.imperative ? section('imperative', tenseTable('imperative', conj.imperative, result.matches)) : null,
    entry.note ? h('p', { class: 'note' }, entry.note) : null,
    sourceLine(entry),
  );
}

function otherCard(result) {
  return h('article', { class: 'card' },
    cardHead(result.entry),
    matchLine(result),
    result.entry.note ? h('p', { class: 'note' }, result.entry.note) : null,
    sourceLine(result.entry),
  );
}

function sourceLine(entry) {
  if (entry.source !== 'ai') return null;
  return h('p', { class: 'caption' }, 'Generated by AI. It may contain mistakes. Saved on this device so it works offline next time.');
}

const CARD = { noun: nounCard, adjective: adjectiveCard, verb: verbCard, other: otherCard };

// ---------------------------------------------------------------- AI lookups

const AI_PREFIX = 'hataya:ai:v1:';
const aiKey = (q) => AI_PREFIX + (isHebrew(q) ? searchKey(q) : q.trim().toLowerCase());

const fixForm = (f) => (f && typeof f.n === 'string' && f.n.trim() ? { n: f.n.normalize('NFC'), p: f.p || toPlain(f.n) } : null);
const fixSlots = (obj, keys) => {
  if (!obj) return null;
  const out = Object.fromEntries(keys.map((k) => [k, fixForm(obj[k])]));
  return Object.values(out).some(Boolean) ? out : null;
};

/** Convert the API's JSON into the same shape the offline dictionary uses. */
function fromAI(e, i) {
  const entry = {
    id: `ai-${i}`,
    source: 'ai',
    type: CARD[e.type] ? e.type : 'other',
    lemma: fixForm(e.lemma) || { n: '?', p: '?' },
    gloss: e.gloss || '',
    note: e.note || null,
    matchedText: e.matched_form || null,
  };
  if (entry.type === 'noun') {
    entry.gender = GENDER[e.gender] ? e.gender : null;
    entry.plural = fixForm(e.plural);
  } else if (entry.type === 'adjective') {
    entry.forms = fixSlots(e.adjective_forms, SLOTS.present) || { ms: entry.lemma };
  } else if (entry.type === 'verb' && e.verb) {
    entry.root = (e.verb.root || '').replace(/[^א-ת]/g, '');
    entry.binyan = e.verb.binyan;
    entry.conj = {
      past: fixSlots(e.verb.past, SLOTS.past),
      present: fixSlots(e.verb.present, SLOTS.present),
      future: fixSlots(e.verb.future, SLOTS.future),
      imperative: fixSlots(e.verb.imperative, SLOTS.imperative),
      infinitive: fixForm(e.verb.infinitive),
    };
  }
  return { entry, matches: [] };
}

let aiController = null;

async function askAI(query) {
  const cached = store.get(aiKey(query), null);
  if (cached) return cached.map(fromAI);
  if (!navigator.onLine) throw new Error('You’re offline. Connect to the internet to ask AI about words that aren’t in the offline dictionary.');

  aiController?.abort();
  aiController = new AbortController();
  const res = await fetch('api/lookup', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ word: query }),
    signal: aiController.signal,
  });
  let data = null;
  try { data = await res.json(); } catch { /* non-JSON error page */ }
  if (!res.ok) throw new Error(data?.error || `The AI lookup failed (${res.status}).`);
  const entries = Array.isArray(data?.entries) ? data.entries : [];
  store.set(aiKey(query), entries);
  return entries.map(fromAI);
}

